#!/bin/sh
# Regenerate the Homebrew formula + Scoop manifest for a git-ark release.
#
#   scripts/render-tap-files.sh <version> [homebrew-tap-dir] [scoop-bucket-dir]
#
# Fetches the release's SHA256SUMS and writes both tap files with the right
# version, URLs, and checksums — no checksum is ever pasted by hand. Then push
# each tap through git-ark (the script prints the exact commands). Tap dirs
# default to the sibling repos ../homebrew-tap and ../scoop-bucket.
#
# See docs/RELEASING.md.
set -eu

DRY=0
args=""
for a in "$@"; do
  case "$a" in
    --dry-run) DRY=1 ;;
    *) args="$args $a" ;;
  esac
done
# shellcheck disable=SC2086
set -- $args

VERSION="${1:?usage: render-tap-files.sh [--dry-run] <version> [brew-dir] [scoop-dir]}"
case "$VERSION" in v*) ;; *) VERSION="v$VERSION" ;; esac
VER="${VERSION#v}" # bare version, e.g. 0.6.0
MSG="git-ark $VER"

here=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd) # git-ark repo root
BREW_DIR="${2:-$here/../homebrew-tap}"
SCOOP_DIR="${3:-$here/../scoop-bucket}"
REPO="boomctl/git-ark"
BASE="https://github.com/$REPO/releases/download/$VERSION"

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT INT TERM

echo "fetching SHA256SUMS for $VERSION"
curl -fsSL --proto '=https' "$BASE/SHA256SUMS" -o "$tmp/SHA256SUMS" ||
  { echo "no SHA256SUMS for $VERSION — is the release published?" >&2; exit 1; }

sha() { # asset-name -> its hash (fails loudly if the asset is missing)
  h=$(grep " $1\$" "$tmp/SHA256SUMS" | awk '{print $1}')
  [ -n "$h" ] || { echo "no checksum for $1 in SHA256SUMS" >&2; exit 1; }
  printf '%s' "$h"
}

SHA_ARM_MAC=$(sha git-ark-aarch64-apple-darwin)
SHA_X64_MAC=$(sha git-ark-x86_64-apple-darwin)
SHA_ARM_LINUX=$(sha git-ark-aarch64-unknown-linux-musl)
SHA_X64_LINUX=$(sha git-ark-x86_64-unknown-linux-musl)
SHA_WIN=$(sha git-ark-x86_64-pc-windows-msvc.exe)

mkdir -p "$BREW_DIR/Formula"
cat >"$BREW_DIR/Formula/git-ark.rb" <<EOF
# git-ark Homebrew formula — GENERATED by git-ark's scripts/render-tap-files.sh.
# Do not hand-edit; regenerate for a new release rather than patching checksums.
#
#   brew tap boomctl/tap
#   brew install git-ark
class GitArk < Formula
  desc "Write-only backup vault that fronts your own git host"
  homepage "https://github.com/boomctl/git-ark"
  version "$VER"
  license "Apache-2.0"

  on_macos do
    on_arm do
      url "$BASE/git-ark-aarch64-apple-darwin"
      sha256 "$SHA_ARM_MAC"
    end
    on_intel do
      url "$BASE/git-ark-x86_64-apple-darwin"
      sha256 "$SHA_X64_MAC"
    end
  end

  on_linux do
    on_arm do
      url "$BASE/git-ark-aarch64-unknown-linux-musl"
      sha256 "$SHA_ARM_LINUX"
    end
    on_intel do
      url "$BASE/git-ark-x86_64-unknown-linux-musl"
      sha256 "$SHA_X64_LINUX"
    end
  end

  def install
    bin.install Dir["git-ark-*"].first => "git-ark"
  end

  test do
    assert_match "git-ark #{version}", shell_output("#{bin}/git-ark --version")
  end
end
EOF

mkdir -p "$SCOOP_DIR/bucket"
cat >"$SCOOP_DIR/bucket/git-ark.json" <<EOF
{
    "version": "$VER",
    "description": "A write-only backup vault that fronts your own git host",
    "homepage": "https://github.com/boomctl/git-ark",
    "license": "Apache-2.0",
    "architecture": {
        "64bit": {
            "url": "$BASE/git-ark-x86_64-pc-windows-msvc.exe#/git-ark.exe",
            "hash": "$SHA_WIN"
        }
    },
    "bin": "git-ark.exe",
    "checkver": "github",
    "autoupdate": {
        "architecture": {
            "64bit": {
                "url": "https://github.com/boomctl/git-ark/releases/download/v\$version/git-ark-x86_64-pc-windows-msvc.exe#/git-ark.exe"
            }
        },
        "hash": {
            "url": "https://github.com/boomctl/git-ark/releases/download/v\$version/SHA256SUMS"
        }
    }
}
EOF

echo "wrote:"
echo "  $BREW_DIR/Formula/git-ark.rb"
echo "  $SCOOP_DIR/bucket/git-ark.json"
echo

if [ "$DRY" -eq 1 ]; then
  echo "dry-run — publish through git-ark with:"
  echo "  (cd \"$BREW_DIR\"  && git commit -am \"$MSG\" && git push git-ark:homebrew-tap main)"
  echo "  (cd \"$SCOOP_DIR\" && git commit -am \"$MSG\" && git push git-ark:scoop-bucket main)"
  exit 0
fi

# Commit + push each tap file through the git-ark vault (which mirrors to GitHub).
publish() { # <dir> <file-within-repo> <vault-remote>
  ( cd "$1"
    git add "$2"
    if git diff --cached --quiet; then
      echo "  $3: already at $MSG"
    else
      git commit -q -m "$MSG"
      git push "$3" main
      echo "  $3: published $MSG"
    fi )
}

echo "publishing through git-ark:"
publish "$BREW_DIR"  "Formula/git-ark.rb"  git-ark:homebrew-tap
publish "$SCOOP_DIR" "bucket/git-ark.json" git-ark:scoop-bucket
